#: 当前内核定义的全部 capability 位掩码。
ALL_CAPS = (1 << (CAP_LAST_CAP + 1)) - 1


def cap_name(cap):
    """返回单个 capability 编号的名称。"""
    return CAP_NAMES.get(cap, "CAP_UNKNOWN_%d" % cap)


def mask_to_names(mask):
    """把 capability 位掩码展开为名称列表（按编号升序）。"""
    names = []
    bit = 0
    while mask:
        if mask & 1:
            names.append(cap_name(bit))
        mask >>= 1
        bit += 1
    return names


def names_to_mask(names):
    """把名称列表折叠为位掩码，未知名称抛 KeyError。"""
    lookup = {v: k for k, v in CAP_NAMES.items()}
    mask = 0
    for name in names:
        mask |= 1 << lookup[name]
    return mask
